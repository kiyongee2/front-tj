//산술 연산자
let x = 10;
let y = 3;

console.log("x + y =", x + y); // 덧셈
console.log("x - y =", x - y); // 뺄셈
console.log("x * y =", x * y); // 곱셈
console.log("x / y =", x / y); // 나눗셈
console.log("x % y =", x % y); // 나머지
console.log("x ** y =", x ** y); // 거듭제곱

//증감 연산자
let a = 5;
console.log("a =", a); // a = 5
a++;
console.log("a =", a); // a = 6 (후위 증가 연산자, a의 값을 먼저 사용한 후에 증가)
a--;
console.log("a =", a); // a = 5 (후위 감소 연산자, a의 값을 먼저 사용한 후에 감소)

//복합 대입 연산자
let b = 10;
console.log("b =", b); // b = 10
b += 5;
console.log("b =", b); // b = 15
b -= 3;
console.log("b =", b); // b = 12
b *= 2;
console.log("b =", b); // b = 24
b /= 4;
console.log("b =", b); // b = 6
b %= 3;
console.log("b =", b); // b = 0



